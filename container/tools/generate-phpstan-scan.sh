#!/usr/bin/env bash
# version 0.1.0
# Regenerate container/phpstan.neon: symbol discovery by scanDirectories,
# one entry for src/ plus one per hidden folder under src/ that holds PHP.
#
# Why the hidden folders are listed by name: when PHPStan walks a folder it
# skips every folder whose name starts with a dot, so `- src` alone never
# reads every .php folder under src/ and the other engine folders (that is what
# made directory scanning look "unreliable" before). Named directly, a
# hidden folder is walked like any other.
#
# The old explicit scanFiles list went stale with every added or deleted
# file: a deleted file stops PHPStan ("Scanned file ... does not exist"),
# a new one is reported as class.notFound. Folders only change when an
# engine folder is added or removed.
#
# Usage:
#   ./generate-phpstan-scan.sh
#
# Run it after adding or removing a hidden folder with PHP files under src/.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"
cd ..  # tools live in tools/; project root (compose file, src/) is the runtime cwd

HEADER="$(cat <<'EOF'
# PHPStan configuration for the php_engine container.
#
# The codebase has no Composer autoloader: pages pull classes/functions
# via require_once chains. Without symbol discovery phpstan reports
# every cross-file symbol as unknown (class.notFound/function.notFound),
# drowning the real findings.
#
# Discovery is scanDirectories: src plus every hidden folder under src
# that holds PHP, listed by name because a folder walk skips dot-folders.
# Generated by ./tools/generate-phpstan-scan.sh; rerun it after adding or
# removing such a folder (a listed folder that is gone stops the run).
#
# Level is NOT pinned here on purpose: lint-static.sh passes --level
# explicitly (default 1); keep tuning it there.
parameters:
    scanDirectories:
        - "src"
EOF
)"

hidden_php_dirs() {
  # Hidden folders at any depth (not inside another hidden folder) that
  # contain at least one .php file; .css/.js asset folders are left out.
  find -P src -name '.*' -type d -prune -print0 \
    | LC_ALL=C sort -z \
    | while IFS= read -r -d '' d; do
        if [ -n "$(find -P "$d" -name '*.php' -type f -print -quit)" ]; then
          printf '        - "%s"\n' "$d"
        fi
      done
}

tmp="$(mktemp phpstan.neon.XXXXXX)"
trap 'rm -f "$tmp"' EXIT
{
  printf '%s\n' "$HEADER"
  hidden_php_dirs
} > "$tmp"
python3 -c "
import sys
try:
    import yaml
except ImportError:
    print('(pyyaml missing: skipped YAML validation)')
    raise SystemExit(0)
d = yaml.safe_load(open(sys.argv[1]))
dirs = d['parameters']['scanDirectories']
assert isinstance(dirs, list) and dirs[0] == 'src', dirs
print('YAML valid.')
" "$tmp"
chmod 644 "$tmp"
mv "$tmp" phpstan.neon
trap - EXIT
echo "Wrote phpstan.neon: $(grep -c '^        - ' phpstan.neon) scanDirectories entries."
